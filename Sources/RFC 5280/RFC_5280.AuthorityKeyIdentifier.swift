// RFC_5280.AuthorityKeyIdentifier.swift
// RFC 5280 §4.2.1.1 — Authority Key Identifier
// https://www.rfc-editor.org/rfc/rfc5280#section-4.2.1.1

public import ISO_8824
public import ISO_8825

extension RFC_5280 {
    /// `AuthorityKeyIdentifier ::= SEQUENCE { keyIdentifier [0] KeyIdentifier
    /// OPTIONAL, authorityCertIssuer [1] GeneralNames OPTIONAL,
    /// authorityCertSerialNumber [2] CertificateSerialNumber OPTIONAL }` with
    /// `KeyIdentifier ::= OCTET STRING` (RFC 5280 §4.2.1.1).
    ///
    /// Criticality law: conforming CAs MUST mark this extension
    /// non-critical. The `keyIdentifier` field MUST be present in all
    /// certificates generated by conforming CAs except self-signed
    /// certificates, and `authorityCertIssuer`/`authorityCertSerialNumber`
    /// appear together when present.
    public struct AuthorityKeyIdentifier: Hashable, Sendable {
        /// The issuer key identifier, typically derived from the issuer's
        /// public key per the §4.2.1.2 methods.
        public var keyIdentifier: ISO_8824.OctetString?

        /// The issuer of the authority's own certificate.
        public var authorityCertIssuer: [RFC_5280.GeneralName]?

        /// The serial number of the authority's own certificate.
        public var authorityCertSerialNumber: RFC_5280.Certificate.SerialNumber?

        public init(
            keyIdentifier: ISO_8824.OctetString? = nil,
            authorityCertIssuer: [RFC_5280.GeneralName]? = nil,
            authorityCertSerialNumber: RFC_5280.Certificate.SerialNumber? = nil
        ) {
            self.keyIdentifier = keyIdentifier
            self.authorityCertIssuer = authorityCertIssuer
            self.authorityCertSerialNumber = authorityCertSerialNumber
        }
    }
}

extension RFC_5280.AuthorityKeyIdentifier: ISO_8825.DER.ImplicitlyTaggable {
    public static var defaultIdentifier: ISO_8824.Identifier {
        .sequence
    }

    public init(derEncoded node: ISO_8825.Node, withIdentifier identifier: ISO_8824.Identifier) throws(ISO_8824.Error) {
        self = try ISO_8825.DER.sequence(node, identifier: identifier) { (nodes: inout ISO_8825.Node.Collection.Iterator) throws(ISO_8824.Error) -> Self in
            let keyIdentifier: ISO_8824.OctetString? = try ISO_8825.DER.optionalImplicitlyTagged(
                &nodes,
                tag: ISO_8824.Identifier(tagWithNumber: 0, tagClass: .contextSpecific)
            )
            let authorityCertIssuer = try ISO_8825.DER.optionalImplicitlyTagged(&nodes, tagNumber: 1, tagClass: .contextSpecific) {
                (node: ISO_8825.Node) throws(ISO_8824.Error) -> [RFC_5280.GeneralName] in
                try ISO_8825.DER.sequence(
                    of: RFC_5280.GeneralName.self,
                    identifier: ISO_8824.Identifier(tagWithNumber: 1, tagClass: .contextSpecific),
                    rootNode: node
                )
            }
            let authorityCertSerialNumber: RFC_5280.Certificate.SerialNumber? = try ISO_8825.DER.optionalImplicitlyTagged(
                &nodes,
                tag: ISO_8824.Identifier(tagWithNumber: 2, tagClass: .contextSpecific)
            )
            return Self(
                keyIdentifier: keyIdentifier,
                authorityCertIssuer: authorityCertIssuer,
                authorityCertSerialNumber: authorityCertSerialNumber
            )
        }
    }

    public func serialize(into coder: inout ISO_8825.DER.Serializer, withIdentifier identifier: ISO_8824.Identifier) throws(ISO_8824.Error) {
        try coder.appendConstructedNode(identifier: identifier) { (coder: inout ISO_8825.DER.Serializer) throws(ISO_8824.Error) in
            try coder.serializeOptionalImplicitlyTagged(
                self.keyIdentifier,
                withIdentifier: ISO_8824.Identifier(tagWithNumber: 0, tagClass: .contextSpecific)
            )
            if let authorityCertIssuer = self.authorityCertIssuer {
                try coder.appendConstructedNode(identifier: ISO_8824.Identifier(tagWithNumber: 1, tagClass: .contextSpecific)) { (coder: inout ISO_8825.DER.Serializer) throws(ISO_8824.Error) in
                    for name in authorityCertIssuer {
                        try coder.serialize(name)
                    }
                }
            }
            try coder.serializeOptionalImplicitlyTagged(
                self.authorityCertSerialNumber,
                withIdentifier: ISO_8824.Identifier(tagWithNumber: 2, tagClass: .contextSpecific)
            )
        }
    }
}

extension RFC_5280.AuthorityKeyIdentifier {
    /// `id-ce-authorityKeyIdentifier` (§4.2.1.1).
    public static var extensionID: ISO_8824.ObjectIdentifier {
        RFC_5280.Extension.ID.authorityKeyIdentifier
    }

    /// Decodes the typed value from a generic ``RFC_5280/Extension``.
    public init(_ certificateExtension: RFC_5280.Extension) throws(ISO_8824.Error) {
        guard certificateExtension.extnID == Self.extensionID else {
            throw ISO_8824.Error.invalidASN1Object(reason: "Expected id-ce-authorityKeyIdentifier, got \(certificateExtension.extnID)")
        }
        self = try Self(derEncoded: certificateExtension.extnValue.bytes)
    }

    /// Wraps this value as a generic ``RFC_5280/Extension``.
    ///
    /// §4.2.1.1 criticality law: conforming CAs MUST mark this extension
    /// non-critical, hence the default.
    public func makeExtension(critical: Bool = false) throws(ISO_8824.Error) -> RFC_5280.Extension {
        var serializer = ISO_8825.DER.Serializer()
        try serializer.serialize(self)
        return RFC_5280.Extension(
            extnID: Self.extensionID,
            critical: critical,
            extnValue: ISO_8824.OctetString(contentBytes: serializer.serializedBytes[...])
        )
    }
}
